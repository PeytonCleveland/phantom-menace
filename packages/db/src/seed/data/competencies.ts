export const competencies: CompetencySeed[] = Object.entries(taxonomy).flatMap(
  ([domainCode, entries]) =>
    entries.map((entry) => {
      const item: CompetencyEntry = typeof entry === "string" ? { name: entry } : entry;
      return {
        code: `${domainCode}.${item.slug ?? slugify(item.name)}`,
        name: item.name,
        primaryDomainCode: domainCode,
        description: item.description ?? "",
        outcomeStatement: item.outcomeStatement ?? "",
      };
    }),
);
